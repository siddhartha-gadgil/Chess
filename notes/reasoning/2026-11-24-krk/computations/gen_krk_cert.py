"""Generate the KRK certificate data for Lean (untrusted; the Lean kernel checks it).
Adapted from notes/reasoning/2026-11-20-kqk-oracle/computations/gen_lean_cert.py.

Reads krk_wtm.tsv (oracle output: wk wr bk dtm src dst) and writes
LeanTheory/Certificates/Chess/KRKData.lean: one hex literal per white-king square, entry
i = 4096*wk + 64*wr + bk at bit offset 32*(64*wr + bk), entry = dtm + 32*src + 2048*dst.
Also writes the chunk files LeanTheory/Certificates/Chess/KRKChunks/C{k}.lean.
"""
import sys, pathlib
root = pathlib.Path(sys.argv[1])
tsv = pathlib.Path(__file__).with_name('krk_wtm.tsv')
rows = [0] * 64
n = 0
for line in tsv.read_text().splitlines():
    if line.startswith('#'):
        continue
    wk, wq, bk, d, src, dst = map(int, line.split())
    assert 1 <= d <= 16 and 0 <= src < 64 and 0 <= dst < 64 and src in (wk, wq)
    e = d + 32 * src + 2048 * dst
    assert e < 2 ** 32
    rows[wk] |= e << (32 * (64 * wq + bk))
    n += 1
assert n == 175168, n
# self-check of the encoding
for line in tsv.read_text().splitlines()[1:200]:
    wk, wq, bk, d, src, dst = map(int, line.split())
    e = (rows[wk] >> (32 * (64 * wq + bk))) % 2 ** 32
    assert (e % 32, e // 32 % 64, e // 2048 % 64) == (d, src, dst)

hdr = '''/-
Copyright (c) 2026 LeanTheory contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: LeanTheory contributors
-/
'''
out = [hdr, 'module\n\npublic import LeanTheory.Certificates.Chess.KRKCheck\n\n',
       '/-!\n# KRK certificate data (generated)\n\n',
       'Generated by `notes/reasoning/2026-11-24-krk/computations/gen_krk_cert.py` from the\n',
       'untrusted retrograde oracle (`N-10`). Entry `i = 4096 wk + 64 wr + bk` is a 32-bit field of\n',
       '`krkRow wk`: depth (5 bits), source and destination squares of White\'s move (6 bits each);\n',
       'depth `0` means no claim. The data is not trusted: `krkStateOK` checks every entry.\n-/\n\n',
       'set_option linter.style.longLine false\n\n',
       '@[expose] public section\n\nnamespace LeanTheory.Chess\n\n']
for wk in range(64):
    out.append(f'/-- KRK table row for the white king on square {wk}. -/\n')
    out.append(f'def krkRow{wk} : Nat := 0x{rows[wk]:x}\n\n')
out.append('/-- The KRK table row for the white king on square `wk`. -/\ndef krkRow (wk : Nat) : Nat :=\n  match wk with\n')
for wk in range(64):
    out.append(f'  | {wk} => krkRow{wk}\n')
out.append('  | _ => 0\n\n')
out.append('/-- The KRK table: entry `i` (32 bits). -/\n'
           'def krkTable (i : Nat) : Nat := (krkRow (i / 4096) >>> (32 * (i % 4096))) % 4294967296\n\n')
out.append('''/-- Coverage of entry `i`: if the three squares are distinct and the black king is not attacked
(a well-formed position with White to move), the entry makes a claim (nonzero depth). -/
def krkCoverOK (T : Nat → Nat) (i : Nat) : Bool :=
  sqOf (i / 4096) == sqOf (i / 64) || sqOf (i / 4096) == sqOf i || sqOf (i / 64) == sqOf i ||
    attackedBy (krkBoard (sqOf (i / 4096)) (sqOf (i / 64)) (sqOf i)) .white (sqOf i) ||
    krkDepth (T i) != 0

/-- All entries with the white king on `wk` and the rook on `wq` pass `krkStateOK` and `krkCoverOK`. -/
def krkRowOK (wk wq : Nat) : Bool :=
  (List.range 64).all fun bk =>
    krkStateOK krkTable (wk * 4096 + wq * 64 + bk) && krkCoverOK krkTable (wk * 4096 + wq * 64 + bk)

/-- All entries with the white king on square `wk` pass `krkStateOK` and `krkCoverOK`. -/
def krkChunkOK (wk : Nat) : Bool := (List.range 64).all fun wq => krkRowOK wk wq

''')
out.append('end LeanTheory.Chess\n')
(root / 'LeanTheory/Certificates/Chess/KRKData.lean').write_text(''.join(out))
chunkdir = root / 'LeanTheory/Certificates/Chess/KRKChunks'
chunkdir.mkdir(exist_ok=True)
for wk in range(64):
    rowthms = '\n\n'.join(f'/-- Entries with the white king on {wk} and the rook on {wq} pass. -/\n'
                       f'theorem krk_row_{wk}_{wq} : krkRowOK {wk} {wq} = true := by kernel_fact'
                       for wq in range(64))
    cases = '\n'.join(f'  | {wq}, _ => exact krk_row_{wk}_{wq}' for wq in range(64))
    (chunkdir / f'C{wk:02d}.lean').write_text(hdr + f'''module

public import LeanTheory.Certificates.Chess.KRKData
public import LeanTheory.Certificates.KernelFact

/-!
# KRK certificate chunk {wk} (generated)

Kernel check (`kernel_fact`, no `decide`) of all table entries with the white king on square
{wk}, one declaration per queen square (the kernel's caches are per declaration, which bounds
memory). Generated by `gen_lean_cert.py`.
-/

@[expose] public section

namespace LeanTheory.Chess

{rowthms}

/-- Every KRK table entry with the white king on square {wk} passes the check. -/
theorem krk_chunk_{wk} : krkChunkOK {wk} = true := by
  simp only [krkChunkOK, List.all_eq_true, List.mem_range]
  intro wq hwq
  match wq, hwq with
{cases}
  | _ + 64, h => exact absurd h (by omega)

end LeanTheory.Chess
''')
print('rows written; total hex chars', sum(len(f'{r:x}') for r in rows))
