"""Generate the KQK certificate data for Lean (untrusted; the Lean kernel checks it).

Reads kqk_wtm.tsv (oracle output: wk wq bk dtm src dst) and writes
LeanTheory/Certificates/Chess/KQKData.lean: one hex literal per white-king square, entry
i = 4096*wk + 64*wq + bk at bit offset 16*(64*wq + bk), entry = dtm + 16*src + 1024*dst.
Also writes the chunk files LeanTheory/Certificates/Chess/KQKChunks/C{k}.lean.
"""
import sys, pathlib
root = pathlib.Path(sys.argv[1])
tsv = pathlib.Path(__file__).with_name('kqk_wtm.tsv')
rows = [0] * 64
n = 0
for line in tsv.read_text().splitlines():
    if line.startswith('#'):
        continue
    wk, wq, bk, d, src, dst = map(int, line.split())
    assert 1 <= d <= 10 and 0 <= src < 64 and 0 <= dst < 64 and src in (wk, wq)
    e = d + 16 * src + 1024 * dst
    assert e < 65536
    rows[wk] |= e << (16 * (64 * wq + bk))
    n += 1
assert n == 144508, n
# self-check of the encoding
for line in tsv.read_text().splitlines()[1:200]:
    wk, wq, bk, d, src, dst = map(int, line.split())
    e = (rows[wk] >> (16 * (64 * wq + bk))) % 65536
    assert (e % 16, e // 16 % 64, e // 1024 % 64) == (d, src, dst)

hdr = '''/-
Copyright (c) 2026 LeanTheory contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: LeanTheory contributors
-/
'''
out = [hdr, 'module\n\npublic import LeanTheory.Certificates.Chess.KQKCheck\n\n',
       '/-!\n# KQK certificate data (generated)\n\n',
       'Generated by `notes/reasoning/2026-11-20-kqk-oracle/computations/gen_lean_cert.py` from the\n',
       'untrusted retrograde oracle (`N-06`). Entry `i = 4096 wk + 64 wq + bk` is a 16-bit field of\n',
       '`kqkRow wk`: depth (4 bits), source and destination squares of White\'s move (6 bits each);\n',
       'depth `0` means no claim. The data is not trusted: `stateOK` checks every entry.\n-/\n\n',
       'set_option linter.style.longLine false\n\n',
       '@[expose] public section\n\nnamespace LeanTheory.Chess\n\n']
for wk in range(64):
    out.append(f'/-- KQK table row for the white king on square {wk}. -/\n')
    out.append(f'def kqkRow{wk} : Nat := 0x{rows[wk]:x}\n\n')
out.append('/-- The KQK table row for the white king on square `wk`. -/\ndef kqkRow (wk : Nat) : Nat :=\n  match wk with\n')
for wk in range(64):
    out.append(f'  | {wk} => kqkRow{wk}\n')
out.append('  | _ => 0\n\n')
out.append('/-- The KQK table: entry `i` (16 bits). -/\n'
           'def kqkTable (i : Nat) : Nat := (kqkRow (i / 4096) >>> (16 * (i % 4096))) % 65536\n\n')
out.append('''/-- Coverage of entry `i`: if the three squares are distinct and the black king is not attacked
(a well-formed position with White to move), the entry makes a claim (nonzero depth). -/
def coverOK (T : Nat → Nat) (i : Nat) : Bool :=
  sqOf (i / 4096) == sqOf (i / 64) || sqOf (i / 4096) == sqOf i || sqOf (i / 64) == sqOf i ||
    attackedBy (kqkBoard (sqOf (i / 4096)) (sqOf (i / 64)) (sqOf i)) .white (sqOf i) ||
    entDepth (T i) != 0

/-- All entries with the white king on square `wk` pass `stateOK` and `coverOK`. -/
def chunkOK (wk : Nat) : Bool :=
  (List.range 4096).all fun j => stateOK kqkTable (wk * 4096 + j) && coverOK kqkTable (wk * 4096 + j)

''')
out.append('end LeanTheory.Chess\n')
(root / 'LeanTheory/Certificates/Chess/KQKData.lean').write_text(''.join(out))
chunkdir = root / 'LeanTheory/Certificates/Chess/KQKChunks'
chunkdir.mkdir(exist_ok=True)
for wk in range(64):
    (chunkdir / f'C{wk:02d}.lean').write_text(hdr + f'''module

public import LeanTheory.Certificates.Chess.KQKData
public import LeanTheory.Certificates.KernelFact

/-!
# KQK certificate chunk {wk} (generated)

Kernel check (`kernel_fact`, no `decide`) of all table entries with the white king on square
{wk}. Generated by `gen_lean_cert.py`.
-/

@[expose] public section

namespace LeanTheory.Chess

/-- Every KQK table entry with the white king on square {wk} passes the check. -/
theorem kqk_chunk_{wk} : chunkOK {wk} = true := by kernel_fact

end LeanTheory.Chess
''')
print('rows written; total hex chars', sum(len(f'{r:x}') for r in rows))
